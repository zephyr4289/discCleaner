/// Framebuffer console.
pub struct Console {
    pub fb: *mut u32,
    pub width: usize,
    pub height: usize,
    pub stride_px: usize,
    pub cx: usize,
    pub cy: usize,
    pub fg: u32,
    pub bg: u32,
}

impl Console {
    /// # Safety
    /// `fb` must point to `height × stride_px` writable pixels for the
    /// lifetime of the console (the UEFI GOP linear buffer).
    pub unsafe fn new(fb: *mut u32, width: usize, height: usize, stride_px: usize) -> Self {
        Self {
            fb,
            width,
            height,
            stride_px,
            cx: 0,
            cy: 0,
            fg: 0xFF_DD_E8_4A, // amber on navy — visible on any panel
            bg: 0xFF_12_14_18,
        }
    }

    pub fn clear(&mut self) {
        for y in 0..self.height {
            for x in 0..self.width {
                unsafe {
                    *self.fb.add(y * self.stride_px + x) = self.bg;
                }
            }
        }
        self.cx = 0;
        self.cy = 0;
    }

    pub fn putc(&mut self, c: u8) {
        if c == b'\n' {
            self.cx = 0;
            self.cy += GLYPH_H;
            return;
        }
        let glyph = if (32..123).contains(&c) {
            &FONT[(c - 32) as usize]
        } else {
            &FONT[0]
        };
        let (gx, gy) = (self.cx, self.cy);
        if gx + GLYPH_W > self.width || gy + GLYPH_H > self.height {
            return;
        }
        for row in 0..GLYPH_H {
            let bits = glyph[row];
            for col in 0..GLYPH_W {
                let on = (bits >> (7 - col)) & 1 == 1;
                let px = gx + col;
                let py = gy + row;
                unsafe {
                    *self.fb.add(py * self.stride_px + px) = if on { self.fg } else { self.bg };
                }
            }
        }
        self.cx += GLYPH_W;
        if self.cx + GLYPH_W > self.width {
            self.cx = 0;
            self.cy += GLYPH_H;
        }
    }

    pub fn puts(&mut self, s: &str) {
        for b in s.as_bytes() {
            self.putc(*b);
        }
    }

    /// Horizontal progress bar (row y, 0..1000 permille).
    pub fn progress(&mut self, y: usize, permille: u32) {
        let y = y.min(self.height.saturating_sub(4));
        for x in 0..self.width {
            let filled = (x as u64 * 1000 / self.width.max(1) as u64) as u32 <= permille;
            let c = if filled { self.fg } else { self.bg };
            for dy in 0..4 {
                unsafe {
                    *self.fb.add((y + dy) * self.stride_px + x) = c;
                }
            }
        }
    }

    pub fn rows(&self) -> usize {
        self.height / GLYPH_H
    }

    pub fn cols(&self) -> usize {
        self.width / GLYPH_W
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_ascii_without_oob() {
        // 64×32 fake framebuffer; write every supported char and wrap.
        let mut fb = vec![0u32; 64 * 32];
        let mut con = unsafe { Console::new(fb.as_mut_ptr(), 64, 32, 64) };
        con.clear();
        for i in 32..123u8 {
            con.putc(i);
        }
        con.puts("\nghost boot ready");
        assert_eq!(con.cols(), 8);
        assert_eq!(con.rows(), 2);
        // Something drew.
        assert!(fb.iter().any(|&p| p != 0xFF_12_14_18));
    }

    #[test]
    fn progress_bar_clamps() {
        let mut fb = vec![0u32; 64 * 32];
        let mut con = unsafe { Console::new(fb.as_mut_ptr(), 64, 32, 64) };
        con.clear();
        con.progress(1000, 500);
        con.progress(0, 1000);
        assert!(fb.contains(&0xFF_DD_E8_4A));
    }
}
