//! SHA-256 (FIPS 180-4) + HMAC-SHA256, dependency-free.
//!
//! Used for: payload manifest hashing (the proof-of-erasure chain of trust
//! anchors on "the kernel that ran is the kernel we reviewed"), vendor
//! Boot-ROM challenge/response authentication, and the Merkle tree over
//! per-block erasure attestations.

